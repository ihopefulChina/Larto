export const MESSAGES: Record<ResolvedLanguage, Record<I18nKey, string>> = {
  'zh-CN': zhCN,
  'en-US': enUS
}

export function resolveLanguage(setting: Language, systemLocale: string): ResolvedLanguage {
  if (setting !== 'system') return setting
  return systemLocale.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en-US'
}

export function translate(lang: ResolvedLanguage, key: I18nKey): string {
  return MESSAGES[lang][key] ?? MESSAGES['zh-CN'][key] ?? key
}
